const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const cid='reed',a={id:'image1',sha256:'current',previous_versions:[{sha256:'old'}],character_ids:[cid],type:'Portrait / likeness',status:'Candidate'};
const c={id:cid,name:'Reed',candidate_ids:[a.id]};
const ctx={location:{protocol:'http:'},review:{notes:{}},current:cid,assets:new Map([[a.id,a]]),people:new Map([[cid,c]]),D:{characters:[c]},types:['Portrait / likeness'],esc:String,canonCurrent:()=>({}),knownSourceHash:(a,h)=>h===a.sha256||a.previous_versions.some(v=>v.sha256===h),window:{dispatchEvent(){}},Event:class{}};
vm.createContext(ctx);
vm.runInContext(code.slice(code.indexOf('function effectiveStatus'),code.indexOf('function updateFamilyConfirmation')),ctx);
